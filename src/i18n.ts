export const tFor = (lang: Lang) => (k: string): string =>
  (STR[lang] && STR[lang][k]) || STR.en[k] || k;

export const tpFor = (lang: Lang) => (k: string, vars: Record<string, string | number>): string => {
  let s = tFor(lang)(k);
  for (const q in vars) s = s.split('{' + q + '}').join(String(vars[q]));
  return s;
};
